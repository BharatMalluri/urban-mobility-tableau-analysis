import pandas as pd
df = pd.read_csv('/content/Monthly_Modal_Time_Series_20260928.csv')

print(f"Original: {len(df):,} rows")

df = df.drop_duplicates()

print(f"Original: {len(df):,} rows")
print(f"Years: {sorted(df['Year'].unique())}")
df = df.query('Year in [2016, 2017]')
print(f"2016-2017: {len(df):,} rows")

df = df.drop_duplicates()

df['Unlinked Passenger Trips'] = df['Unlinked Passenger Trips'].apply(lambda x: float(str(x).replace(',', '')))
df = df[df['Unlinked Passenger Trips'] > 0]

rows = len(df)
agencies = df['Agency'].nunique()
modes = df['Mode'].nunique()
print(f"Cleaned: {rows:,} rows")
print(f"Agencies: {agencies}")
print(f"Modes: {modes}")
print("\nTop 15 agencies:")
top = df.groupby('Agency')['Unlinked Passenger Trips'].sum().sort_values(ascending=False).head(15).reset_index()
for i, row in top.iterrows():
    print(f"{i+1}. {row['Agency']}: {row['Unlinked Passenger Trips']:,.0f}")
top_agencies = df.groupby('Agency')['Unlinked Passenger Trips'].sum().sort_values(ascending=False).head(10).index
df = df[df['Agency'].isin(top_agencies)]
print(f"Final dataset: {len(df):,} rows")
print(f"Agencies: {df['Agency'].nunique()}")
print(f"Modes: {df['Mode'].nunique()}")
print(f"Years: {sorted(df['Year'].unique())}")

df.filter(['Year', 'Month', 'Mode', 'Agency', 'Unlinked Passenger Trips', 'Vehicle Revenue Hours', 'Vehicle Revenue Miles']).to_csv('/content/NTD_2016_2017_Top10_Cleaned.csv', index=False)
print(f"Exported: {len(df):,} rows")